import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source = readFileSync(new URL('../Linux/extension/retro-terminal@vibeware.local/guard.js', import.meta.url), 'utf8');
const {surfaceAllowed, DelayGuard, MAX_DESKTOP_PIXELS, MAX_STAGE_PIXELS} = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
assert(surfaceAllowed(1920, 1080, 1));
assert(surfaceAllowed(3840, 2160, 1));
assert(!surfaceAllowed(3840, 2160, 2));
assert(!surfaceAllowed(7680, 2160, 1));
assert(surfaceAllowed(4920, 2160, 1, MAX_DESKTOP_PIXELS), 'Allow a 4K and portrait desktop layout');
assert(surfaceAllowed(6400, 1440, 2, MAX_DESKTOP_PIXELS, 16384), 'Allow the scaled three-display desktop');
assert(surfaceAllowed(6404, 1444, 2, MAX_STAGE_PIXELS, 16384), 'Allow the padded three-display compositor texture');
assert(!surfaceAllowed(7684, 2164, 2, MAX_STAGE_PIXELS, 16384), 'Reject oversized compositor textures');
assert(surfaceAllowed(4484, 1444, 2, MAX_STAGE_PIXELS, 16384), 'Bound the scaled compositor texture independently');
assert(!surfaceAllowed(7680, 2160, 2, MAX_STAGE_PIXELS, 16384));
for (const invalid of [NaN, Infinity, 0, -1]) assert(!surfaceAllowed(invalid, 1080, 1));
let guard = new DelayGuard(0);
assert(!guard.sample(0.25));
assert(!guard.sample(0.8));
assert(!guard.sample(1.35));
assert(guard.sample(1.9));
guard = new DelayGuard(0);
assert(guard.sample(2));
guard = new DelayGuard(0);
assert(!guard.sample(0.6));
assert(!guard.sample(0.85));
assert(!guard.sample(1.4));
assert(!guard.sample(1.65));
console.log('PASS physical surface limits and desktop delay guard');

const recoverySource = readFileSync(new URL('../Linux/extension/retro-terminal@vibeware.local/recovery.js', import.meta.url), 'utf8');
const {RecoveryWindow, parseResources, MAX_RECOVERY_ATTEMPTS} = await import(`data:text/javascript;base64,${Buffer.from(recoverySource).toString('base64')}`);
const memory = 'MemTotal: 8192000 kB\nMemAvailable: 2048000 kB\n';
assert.equal(parseResources('unreadable', memory), null);
assert.equal(parseResources('cpu 10 0 0 90\n', ''), null);
assert.equal(MAX_RECOVERY_ATTEMPTS, 2);
const healthySample = time => parseResources(`cpu ${time + 5} 0 0 ${(time + 5) * 9}\n`, memory);
const recovery = new RecoveryWindow(0, 30, 0);
for (let time = 0; time <= 30; time += 5) assert(!recovery.ready(time, healthySample(time)));
assert(recovery.ready(35, healthySample(35)));
const retry = new RecoveryWindow(0, 30, 1);
for (let time = 0; time < 60; time += 5) assert(!retry.ready(time, healthySample(time)));
assert(retry.ready(60, healthySample(60)));
assert(!retry.ready(65, null));
for (let time = 70; time <= 100; time += 5) assert(!retry.ready(time, healthySample(time)));
assert(retry.ready(105, healthySample(105)));
console.log('PASS bounded recovery delay, continuous stability and unavailable resource handling');
